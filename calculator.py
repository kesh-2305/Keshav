A = int(input("Enter your first number: "))
B = int(input("Enter your second number: "))

opp = input("Enter your operator: ")

if opp == "+" :
    print(A + B)
elif opp == "-" :
    print(A - B)
elif opp == "*" :
    print(A * B)
elif opp == "/" :
    print(A / B)
else :
    print("you enter a wrong opp sir ji")